#!/usr/bin/env python3
"""Build the lean production agent from the annotated source.

    python3 tools/build_agent.py            # write .claude/agents/uat.agent.md
    python3 tools/build_agent.py --check    # exit 1 if the twin is stale

What it removes
  - "#" comment lines inside the YAML frontmatter
  - HTML comments in the body (never inside fenced code blocks)
  - runs of blank lines left behind

What it never touches
  - any instruction text. If the twin and the source ever disagree on a rule,
    the source wins and this script is how you resync them.

Standard library only. If PyYAML happens to be installed the frontmatter is
also parsed as a final check.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SRC = ROOT / "agent-src" / "uat.agent.md"
DEFAULT_OUT = ROOT / ".claude" / "agents" / "uat.agent.md"
BANNER = ("# GENERATED from agent-src/uat.agent.md by tools/build_agent.py.\n"
          "# Edit the source, then rebuild. Do not edit this file by hand.\n")


def split_frontmatter(text):
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise SystemExit("error: source must start with a '---' frontmatter line")
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i], lines[i + 1:]
    raise SystemExit("error: frontmatter is not closed with '---'")


def strip_frontmatter_comments(lines):
    kept = [ln for ln in lines if not ln.lstrip().startswith("#")]
    out = []
    for ln in kept:                      # drop the blank lines comments left behind
        if ln.strip() == "":
            continue
        out.append(ln.rstrip())
    return out


def strip_html_comments(lines):
    """Remove <!-- ... --> outside fenced code blocks, across lines."""
    out, in_fence, in_comment = [], False, False
    for ln in lines:
        if not in_comment and re.match(r"^\s*(```|~~~)", ln):
            in_fence = not in_fence
            out.append(ln)
            continue
        if in_fence:
            out.append(ln)
            continue
        buf, i = "", 0
        while i < len(ln):
            if in_comment:
                end = ln.find("-->", i)
                if end == -1:
                    i = len(ln)
                else:
                    in_comment = False
                    i = end + 3
            else:
                start = ln.find("<!--", i)
                if start == -1:
                    buf += ln[i:]
                    i = len(ln)
                else:
                    buf += ln[i:start]
                    in_comment = True
                    i = start + 4
        had_comment = ("<!--" in ln) or ("-->" in ln) or in_comment
        if had_comment and buf.strip() == "":
            continue                      # the line was only comment
        out.append(buf.rstrip())
    if in_comment:
        raise SystemExit("error: an HTML comment is opened but never closed")
    return out


def collapse_blank_runs(lines):
    out, blank = [], 0
    for ln in lines:
        if ln.strip() == "":
            blank += 1
            if blank > 1:
                continue
        else:
            blank = 0
        out.append(ln)
    while out and out[0].strip() == "":
        out.pop(0)
    while out and out[-1].strip() == "":
        out.pop()
    return out


def build(src_text):
    fm, body = split_frontmatter(src_text)
    fm = strip_frontmatter_comments(fm)
    body = collapse_blank_runs(strip_html_comments(body))
    keys = {ln.split(":", 1)[0].strip() for ln in fm if re.match(r"^[A-Za-z]", ln)}
    for required in ("name", "description"):
        if required not in keys:
            raise SystemExit(f"error: frontmatter is missing required field '{required}'")
    if not body:
        raise SystemExit("error: the body (system prompt) is empty")
    text = "---\n" + BANNER + "\n".join(fm) + "\n---\n\n" + "\n".join(body) + "\n"
    try:                                   # optional deeper check
        import yaml  # type: ignore
        parsed = yaml.safe_load("\n".join(fm))
        if not isinstance(parsed, dict) or not parsed.get("name") or not parsed.get("description"):
            raise SystemExit("error: frontmatter did not parse to a mapping with name and description")
    except ImportError:
        pass
    return text


def words(text):
    return len(re.findall(r"\S+", text))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", type=Path, default=DEFAULT_SRC)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if the twin is missing or stale")
    args = ap.parse_args()

    src_text = args.src.read_text(encoding="utf-8")
    twin = build(src_text)

    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else None
        if current != twin:
            print(f"STALE: {args.out} does not match {args.src}. Run: python3 tools/build_agent.py")
            return 1
        print(f"OK: {args.out} is up to date")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(twin, encoding="utf-8")
    body_words = words(twin.split("\n---\n", 1)[1])
    print(f"wrote {args.out}")
    print(f"source: {words(src_text)} words   twin: {words(twin)} words   system prompt: {body_words} words")
    return 0


if __name__ == "__main__":
    sys.exit(main())
